import Foundation

/// `--selftest` for the clipboard history: what is never recorded, twins, caps, search, titles.
@MainActor
enum ClipboardChecks {
    static func run(_ m: ClipboardModel) -> [String] {
        var f: [String] = []
        func expect(_ ok: Bool, _ message: @autoclosure () -> String) { if !ok { f.append(message()) } }

        // Secrets and temporary data are never recorded.
        expect(ClipboardFilter.isSensitive(["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]), "type confidentiel enregistré")
        expect(ClipboardFilter.isSensitive(["org.nspasteboard.TransientType"]), "type temporaire enregistré")
        expect(ClipboardFilter.isSensitive(["public.png", "org.nspasteboard.AutoGeneratedType"]), "type généré automatiquement enregistré")
        expect(ClipboardFilter.isSensitive(["com.agilebits.onepassword", "public.utf8-plain-text"]), "ancien marqueur 1Password ignoré")
        expect(!ClipboardFilter.isSensitive(["public.utf8-plain-text", "public.html"]), "texte ordinaire refusé")
        let defaults = ClipboardSettings().excluded
        for id in ["com.1password.1password", "com.apple.Passwords", "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.apple.keychainaccess"] {
            expect(ClipboardFilter.isExcluded(id, list: defaults), "gestionnaire de mots de passe non ignoré : \(id)")
        }
        expect(ClipboardFilter.isExcluded("COM.1PASSWORD.1PASSWORD", list: defaults), "exclusion sensible à la casse")
        expect(!ClipboardFilter.isExcluded("com.apple.TextEdit", list: defaults), "TextEdit ignoré à tort")
        expect(!ClipboardFilter.isExcluded(nil, list: defaults), "app inconnue ignorée")
        expect(!ClipboardSettings().enabled, "historique activé par défaut")

        // Titles and kinds.
        expect(ClipboardText.title("\n\n   Bonjour   le\tmonde  \nsuite") == "Bonjour le monde", "titre : \(ClipboardText.title("\n\n   Bonjour   le\tmonde  \nsuite"))")
        expect(ClipboardText.kind(of: "https://exemple.fr/page?x=1") == .link, "lien non reconnu")
        expect(ClipboardText.kind(of: "voir https://exemple.fr") == .plain, "phrase prise pour un lien")
        expect(ClipboardText.kind(of: "#D97757") == .color, "couleur non reconnue")
        expect(ClipboardText.kind(of: "func a() {\n    return b(c)\n}") == .code, "code non reconnu")
        expect(ClipboardText.kind(of: "Une phrase.\nUne autre.") == .plain, "texte pris pour du code")

        // Twins, caps and age.
        let now = Date()
        func item(_ text: String, minutes: Double, pinned: Bool = false) -> ClipboardItem {
            ClipboardItem(kind: .text, text: text, digest: ClipboardStorage.digest(Data(text.utf8)),
                          date: now.addingTimeInterval(-minutes * 60), firstDate: now, pinned: pinned)
        }
        var list = [item("b", minutes: 5), item("a", minutes: 10)]
        let again = ClipboardHistory.insert(item("a", minutes: 0), into: list)
        expect(again.duplicate && again.list.count == 2 && again.list.first?.text == "a" && again.list.first?.count == 2, "doublon ajouté au lieu d'être remonté")
        list = (0..<10).map { item("t\($0)", minutes: Double($0)) } + [item("épingle", minutes: 99_999, pinned: true)]
        let capped = ClipboardHistory.prune(list, maxItems: 4, maxBytes: 1_000_000, retentionDays: 0, now: now)
        expect(capped.kept.count == 5 && capped.kept.contains { $0.pinned }, "plafond d'éléments : \(capped.kept.count) gardés")
        expect(capped.kept.filter { !$0.pinned }.map { $0.text ?? "" } == ["t0", "t1", "t2", "t3"], "les plus récents ne sont pas gardés")
        let aged = ClipboardHistory.prune([item("vieux", minutes: 60 * 24 * 40), item("récent", minutes: 5)], maxItems: 100,
                                          maxBytes: 1_000_000, retentionDays: 30, now: now)
        expect(aged.kept.map { $0.text ?? "" } == ["récent"], "durée de conservation non appliquée")
        let heavy = ClipboardHistory.prune([item(String(repeating: "x", count: 600), minutes: 1), item(String(repeating: "y", count: 600), minutes: 2)],
                                           maxItems: 100, maxBytes: 1000, retentionDays: 0, now: now)
        expect(heavy.kept.count == 1 && heavy.removed.count == 1, "plafond de taille non appliqué")

        // Search, accents and case aside.
        let pool = [item("Été à la plage", minutes: 1), item("Facture Lumière", minutes: 2), item("https://exemple.fr", minutes: 3)]
        let key: (ClipboardItem) -> String = { $0.searchKey }
        expect(ClipboardHistory.search(pool, query: Fuzzy.fold("ete PLAGE"), keys: key, limit: 9).count == 1, "recherche sans accents")
        expect(ClipboardHistory.search(pool, query: "lien", keys: key, limit: 9).first?.text == "https://exemple.fr", "recherche des liens")
        expect(ClipboardHistory.search(pool, query: "", keys: key, limit: 2).count == 2, "limite de recherche")

        // The thumbnail folder only takes bare file names.
        expect(!ClipboardStorage.isPlainName("../secret.png") && !ClipboardStorage.isPlainName("/tmp/x.png") && !ClipboardStorage.isPlainName(".x"),
               "nom de fichier dangereux accepté")
        expect(ClipboardStorage.isPlainName("6F1C-thumb.png"), "nom de vignette refusé")

        // Demo: nothing is read from or written to the real clipboard.
        if DemoData.isEnabled {
            expect(!m.watching, "le presse-papiers est surveillé en démo")
            if let first = m.items.first, case .copied = m.recopy(first) { f.append("la démo a écrit dans le presse-papiers") }
            expect(!ClipboardLauncher.results("cb", model: m).isEmpty, "lanceur « cb » vide en démo")
            expect(ClipboardLauncher.results("cb lumiere", model: m).first?.title.contains("Lumière") == true, "recherche « cb lumiere » en démo")
        }
        return f
    }
}
